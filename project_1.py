# Invoice Generator

products = []

def add_product(name, price, quantity):
    product = {
        "name": name,
        "price": price,
        "quantity": quantity
    }
    products.append(product)

def calculate_total():
    total = 0

    for product in products:
        total = total + product["price"] * product["quantity"]

    return total

# Add products to the invoice
add_product("Notebook", 50, 2)
add_product("Pen", 10, 5)
add_product("Eraser", 5, 3)

# Print the invoice
print("INVOICE")

for product in products:
    amount = product["price"] * product["quantity"]
    print(product["name"], "-", product["quantity"], "x",
          product["price"], "=", amount)

print("Total: Rs.", calculate_total())